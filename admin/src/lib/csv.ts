/** One CSV cell. A leading =, +, -, @, tab or CR would run as a formula when the file opens in Excel, so it is neutralised. */
export function csvCell(v: unknown): string {
  let s = v == null ? "" : String(v);
  if (/^[=+\-@\t\r]/.test(s)) s = `'${s}`;
  return /[",\n]/.test(s) ? `"${s.replace(/"/g, '""')}"` : s;
}
