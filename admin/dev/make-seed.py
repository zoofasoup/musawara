#!/usr/bin/env python3
"""Writes seed-dummy.sql: one made-up client with 60 days of ads data, sales, creatives and alerts,
for looking at the client dashboard locally. Run: python3 dev/make-seed.py > dev/seed-dummy.sql
Apply: npx wrangler d1 execute musawara-ads --local -c wrangler.noR2.jsonc --file admin/dev/seed-dummy.sql (from repo root)."""
import datetime as dt, json, math, random

random.seed(7)
TODAY = dt.date(2026, 11, 18)
DAYS = 75
CID, AID = 900, 900
q = lambda v: "NULL" if v is None else ("'" + str(v).replace("'", "''") + "'" if isinstance(v, str) else repr(v))
out = []
w = out.append

w("-- Dummy data for local development only. Generated by dev/make-seed.py.")
w(f"DELETE FROM alerts WHERE ad_account_id={AID};")
w(f"DELETE FROM sync_jobs WHERE ad_account_id={AID};")
w(f"DELETE FROM insights_daily WHERE ad_account_id={AID};")
w(f"DELETE FROM entities WHERE ad_account_id={AID};")
w(f"DELETE FROM account_settings WHERE ad_account_id={AID};")
w(f"DELETE FROM sales WHERE client_id={CID};")
w(f"DELETE FROM ad_accounts WHERE id={AID};")
w(f"DELETE FROM clients WHERE id={CID};")
w(f"INSERT INTO clients (id,name,slug,brand_color,target_cpa) VALUES ({CID},'Musafar Dummy','musafar-dummy','#7a2de3',500000);")
w(f"INSERT INTO ad_accounts (id,client_id,meta_account_id,account_name) VALUES ({AID},{CID},'act_dummy900','Musafar Ads (dummy)');")
w(f"INSERT INTO account_settings (ad_account_id,primary_result_type,primary_result_label,monthly_budget_idr) VALUES ({AID},'messaging','Leads',30000000);")
w(f"INSERT INTO sync_jobs (ad_account_id,started_at,finished_at,status,rows_upserted) VALUES ({AID},datetime('now','-3 hours'),datetime('now','-3 hours'),'success',120);")

campaigns = [("c_umroh", "Umroh Desember · Leads", 0.55), ("c_retarget", "Retargeting Website", 0.25), ("c_brand", "Awareness Brand", 0.20)]
ads = [("a1", "Video Testimoni Jamaah", True, 0.30, 1.0), ("a2", "Carousel Paket Desember", False, 0.22, 0.9),
       ("a3", "Reels Tips Umroh", True, 0.20, 1.1), ("a4", "Foto Hotel Madinah", False, 0.15, 0.7), ("a5", "Promo Early Bird", False, 0.13, 0.6)]
def thumb(hue):
    svg = f"<svg xmlns='http://www.w3.org/2000/svg' width='320' height='320'><defs><linearGradient id='g' x1='0' y1='0' x2='1' y2='1'><stop offset='0' stop-color='hsl({hue},70%,70%)'/><stop offset='1' stop-color='hsl({(hue+50)%360},65%,45%)'/></linearGradient></defs><rect width='320' height='320' fill='url(#g)'/></svg>"
    return "data:image/svg+xml," + svg.replace("<", "%3C").replace(">", "%3E").replace("#", "%23").replace(" ", "%20")
for i, (eid, name, _) in enumerate(campaigns):
    w(f"INSERT INTO entities (ad_account_id,level,entity_id,name,status,effective_status,objective,daily_budget) VALUES ({AID},'campaign',{q(eid)},{q(name)},'ACTIVE','ACTIVE','OUTCOME_LEADS',{[600000,250000,200000][i]});")
for i, (eid, name, video, _, _) in enumerate(ads):
    w(f"INSERT INTO entities (ad_account_id,level,entity_id,name,status,effective_status,parent_id,thumbnail_url) VALUES ({AID},'ad',{q(eid)},{q(name)},'ACTIVE','{'ACTIVE' if i != 3 else 'PAUSED'}','c_umroh',{q(thumb(250 - i * 45))});")

rows = []
for d in range(DAYS):
    day = TODAY - dt.timedelta(days=DAYS - 1 - d)
    if day >= TODAY: continue
    growth = 0.75 + 0.5 * d / DAYS
    wk = 1.0 + 0.18 * math.sin(d * 2 * math.pi / 7)
    total_spend = 900_000 * growth * wk * random.uniform(0.85, 1.15)
    if day.weekday() == 5: total_spend *= 0.7
    day_s = day.isoformat()
    for cid, cname, share in campaigns:
        spend = total_spend * share * random.uniform(0.9, 1.1)
        cpm = random.uniform(40000, 56000)
        imp = int(spend / cpm * 1000)
        reach = int(imp / random.uniform(1.2, 1.9))
        clicks = int(imp * random.uniform(0.012, 0.022)); link = int(clicks * 0.8)
        cpl = {"c_umroh": 38000, "c_retarget": 52000, "c_brand": 90000}[cid] * random.uniform(0.8, 1.25)
        leads = int(spend / cpl)
        w(f"INSERT INTO insights_daily (ad_account_id,level,entity_id,entity_name,campaign_id,date,spend,impressions,reach,clicks,link_clicks,results,leads) VALUES ({AID},'campaign',{q(cid)},{q(cname)},{q(cid)},{q(day_s)},{spend:.0f},{imp},{reach},{clicks},{link},{leads},{leads});")
    for aid, aname, video, share, quality in ads:
        spend = total_spend * 0.55 * share * random.uniform(0.85, 1.15)
        imp = int(spend / random.uniform(42000, 54000) * 1000)
        reach = int(imp / random.uniform(1.3, 2.0 if aid != "a5" else 4.2))
        link = int(imp * random.uniform(0.008, 0.018) * quality)
        leads = int(spend / (40000 / quality * random.uniform(0.85, 1.2)))
        actions = json.dumps([{"action_type": "video_view", "value": str(int(imp * random.uniform(0.25, 0.4)))}]) if video else None
        extras = json.dumps({"video": {"thruplay": int(imp * 0.06), "plays": int(imp * 0.5), "avg_watch_s": round(random.uniform(3, 7), 1)}, "rank": {"quality": "AVERAGE", "engagement": "ABOVE_AVERAGE_35" if quality > 0.9 else "BELOW_AVERAGE_20", "conversion": "AVERAGE"}}) if video else json.dumps({"rank": {"quality": "AVERAGE", "engagement": "AVERAGE", "conversion": "AVERAGE"}})
        w(f"INSERT INTO insights_daily (ad_account_id,level,entity_id,entity_name,parent_id,campaign_id,date,spend,impressions,reach,clicks,link_clicks,results,leads,actions_json,extras_json) VALUES ({AID},'ad',{q(aid)},{q(aname)},'c_umroh','c_umroh',{q(day_s)},{spend:.0f},{imp},{reach},{link},{link},{leads},{leads},{q(actions)},{q(extras)});")

n = 0
for d in range(DAYS):
    day = TODAY - dt.timedelta(days=DAYS - 1 - d)
    if day >= TODAY: continue
    k = random.choices([0, 1, 2, 3, 4], weights=[2, 3, 3, 2, 1])[0] if (d % 11) else 0
    for _ in range(k):
        n += 1
        val = random.choice([27_500_000, 31_000_000, 34_900_000, 38_500_000, 44_000_000, 47_500_000])
        w(f"INSERT INTO sales (client_id,sale_key,sale_date,value,label,source,meta_state,pay_status) VALUES ({CID},'dummy{n}',{q(day.isoformat())},{val},{q(random.choice(['Budi S.','Siti N.','Agus P.','Dewi L.','Rina K.','Hadi M.']))},'Instagram',{q('sent' if random.random() < 0.8 else 'dashboard')},{q(random.choice(['dp','paid','paid']))});")

alerts = [("cpr_spike","critical","CPA naik 22% dibanding periode lalu",0),("creative_fatigue","warning","Foto Hotel Madinah frekuensi 3.8, mulai jenuh",0),
          ("budget_pacing","warning","Budget bulan ini diproyeksikan terlewati 40%",0),("sync_failure","warning","Sync kemarin gagal, sudah pulih",1)]
for i, (t, sev, msg, ack) in enumerate(alerts):
    w(f"INSERT INTO alerts (ad_account_id,entity_id,level,type,severity,message,date,acknowledged,created_at) VALUES ({AID},{q('a4' if t=='creative_fatigue' else None)},NULL,{q(t)},{q(sev)},{q(msg)},{q((TODAY - dt.timedelta(days=i)).isoformat())},{ack},datetime('now','-{i} days'));")
print("\n".join(out))
